import { trimRecording } from '../scripts/trim-recording.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { processVideo, runFFmpeg, localVideoPath, readStyle } from '../scripts/video-processing.mjs';
import { updateRecordings, readRecordings } from '../scripts/recording-store.mjs';
import { rebuildVideos } from '../scripts/rebuild-coach-videos.mjs';

test('real processing keeps original, creates 200-square and 50-square videos with audio, and bulk restyles from source', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'andrew-video-test-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'public/coach/shared/originals'), { recursive: true });
  const style = { size: 200, pixelSize: 50, fps: 12, saturation: 1.1, contrast: 1.05, crf: 26 };
  await writeFile(path.join(root, 'coach-video-style.json'), JSON.stringify(style));
  const original = '/coach/shared/originals/test-take.mp4';
  const input = localVideoPath(root, original);
  await runFFmpeg(['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=320x240:rate=24', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000', '-t', '1', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', input]);
  const bytes = await readFile(input);
  const result = await processVideo(root, original);
  const trimmed = await trimRecording(root, { original, ...result }, 0.25, 0.75);
  const trimmedInfo = await runFFmpeg(['-hide_banner', '-i', localVideoPath(root, trimmed.original), '-f', 'null', '-']);
  assert.match(trimmedInfo, /Duration: 00:00:00\.5/);
  assert.match(trimmedInfo, /Audio: aac/);
  assert.equal(trimmed.trimSource.original, original);
  assert.notEqual(trimmed.variants.pixel32.video, result.variants.pixel32.video);
  assert.deepEqual(await readFile(input), bytes);
  const info = await runFFmpeg(['-hide_banner', '-i', localVideoPath(root, result.video), '-f', 'null', '-']);
  assert.match(info, /200x200/);
  assert.match(info, /12 fps/);
  assert.match(info, /Audio: aac/);
  const small = result.variants.pixel50;
  const smallInfo = await runFFmpeg(['-hide_banner', '-i', localVideoPath(root, small.video), '-f', 'null', '-']);
  assert.match(smallInfo, /50x50/);
  assert.match(smallInfo, /Audio: aac/);
  const natural = result.variants.natural100;
  const naturalInfo = await runFFmpeg(['-hide_banner', '-i', localVideoPath(root, natural.video), '-f', 'null', '-']);
  assert.match(naturalInfo, /100x100/);
  assert.match(naturalInfo, /Audio: aac/);
  assert.equal(natural.style.saturation, 1);
  const chunkyInfo = await runFFmpeg(['-hide_banner', '-i', localVideoPath(root, result.variants.pixel32.video), '-f', 'null', '-']);
  assert.match(chunkyInfo, /32x32/);
  assert.match(chunkyInfo, /Audio: aac/);
  assert.notEqual(small.video, result.video);
  assert.deepEqual(await readFile(input), bytes);
  await updateRecordings(root, recordings => { recordings.test = { original, ...result }; });
  await writeFile(path.join(root, 'coach-video-style.json'), JSON.stringify({ ...style, pixelSize: 25 }));
  assert.deepEqual(await rebuildVideos(root, () => {}), { completed: 1, failed: 0 });
  const changed = (await readRecordings(root)).test;
  assert.notEqual(changed.video, result.video);
  assert.notEqual(changed.variants.pixel50.video, result.variants.pixel50.video);
  assert.equal(changed.variants.pixel50.style.size, 50);
  assert.ok((await stat(localVideoPath(root, result.variants.pixel50.video))).size > 0);
  assert.notEqual(changed.styleId, result.styleId);
  assert.equal(changed.original, original);
  assert.ok((await stat(localVideoPath(root, result.video))).size > 0);
  assert.deepEqual(await readFile(input), bytes);
  // A failed bulk conversion does not replace the working styled clip.
  await writeFile(path.join(root, 'public/coach/shared/originals/broken.mp4'), 'invalid');
  await updateRecordings(root, recordings => { recordings.broken = { original: '/coach/shared/originals/broken.mp4', video: '/coach/keep.mp4' }; });
  const failed = await rebuildVideos(root, () => {});
  assert.equal(failed.failed, 1);
  assert.equal((await readRecordings(root)).broken.video, '/coach/keep.mp4');
  assert.throws(() => localVideoPath(root, '/coach/../../outside.mp4'));
  await writeFile(path.join(root, 'coach-video-style.json'), JSON.stringify({ ...style, size: 201 }));
  await assert.rejects(readStyle(root), /even output/);
});
